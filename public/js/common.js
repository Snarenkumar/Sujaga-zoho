function openEvidenceModal(matchId) {
  const modal = document.getElementById('evidence-modal');
  const content = document.getElementById('evidence-content');
  modal.classList.remove('hidden');
  content.innerHTML = '<p class="muted">Loading evidence trail...</p>';

  fetch(`/api/evidence/${matchId}`)
    .then(r => r.json())
    .then(data => {
      content.innerHTML = renderEvidence(data);
    })
    .catch(() => {
      content.innerHTML = '<p class="muted">Failed to load evidence trail.</p>';
    });
}

function closeEvidenceModal() {
  document.getElementById('evidence-modal').classList.add('hidden');
}

function loadEvidencePage(matchId) {
  const el = document.getElementById('evidence-page');
  if (!el) return;
  el.innerHTML = '<p class="muted">Loading...</p>';
  fetch(`/api/evidence/${matchId}`)
    .then(r => r.json())
    .then(data => { el.innerHTML = renderEvidence(data); })
    .catch(() => { el.innerHTML = '<p class="muted">Failed to load.</p>'; });
}

function renderEvidence(data) {
  const { match, fir1, fir2 } = data;
  const pct = Math.round(match.similarity_score * 100);
  const weights = match.reasoning_weights || {};

  let weightsHtml = Object.entries(weights).map(([key, val]) => {
    const label = key.replace(/_/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
    const pctVal = Math.round(val * 100);
    return `<div class="weight-item">
      <span style="min-width:160px">${label}: ${pctVal}%</span>
      <div class="weight-bar"><div class="weight-fill" style="width:${pctVal}%"></div></div>
    </div>`;
  }).join('');

  return `
    <div class="similarity-score">${pct}% Match</div>
    <p class="muted" style="margin:0.5rem 0 1rem">${match.reason}</p>
    <p><strong>Compared FIRs:</strong> ${fir1 ? fir1.fir_no : match.fir_id_1} ↔ ${fir2 ? fir2.fir_no : match.fir_id_2}</p>
    <div class="evidence-compare">
      <div>
        <h4>${fir1 ? fir1.fir_no + ' — ' + fir1.district : match.fir_id_1}</h4>
        <div class="evidence-snippet">${match.mo_snippet_1}</div>
      </div>
      <div>
        <h4>${fir2 ? fir2.fir_no + ' — ' + fir2.district : match.fir_id_2}</h4>
        <div class="evidence-snippet">${match.mo_snippet_2}</div>
      </div>
    </div>
    <h4>Reasoning Weight Breakdown</h4>
    <div class="weights-bar">${weightsHtml}</div>
    <p class="muted" style="font-size:0.75rem;margin-top:1rem">Audit log ID: ${match.id} · Generated by Zoho Catalyst · Timestamp: ${new Date().toISOString()}</p>
  `;
}

function formatBotMessage(text) {
  return text
    .replace(/\*\*(.*?)\*\*/g, '<strong>$1</strong>')
    .replace(/\n/g, '<br>');
}
